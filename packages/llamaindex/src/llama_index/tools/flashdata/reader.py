"""Convert search records and existing captions to LlamaIndex Documents."""

import json
import re
from urllib.parse import urlsplit

from llama_index.core.readers.base import BaseReader
from llama_index.core.schema import Document

from ._catalog import CONTRACTS
from ._execution import Execution

RESULT_FIELDS = {
    "google_search": "organic",
    "google_news": "news",
    "google_images": "images",
    "google_shopping": "shopping",
    "google_videos": "videos",
    "google_places": "places",
    "youtube_search": "results",
    "youtube_search_extended": "results",
}


def _source_metadata(record):
    if not isinstance(record, dict):
        return {}
    meta = {k: record[k] for k in ("title", "videoId", "channelId", "channelUrl") if k in record}
    video_id = record.get("videoId")
    if isinstance(video_id, str) and re.fullmatch(r"[A-Za-z0-9_-]{11}", video_id):
        meta["url"] = f"https://www.youtube.com/watch?v={video_id}"
    else:
        for key in ("link", "url", "channelUrl"):
            value = record.get(key)
            if not isinstance(value, str):
                continue
            try:
                parsed = urlsplit(value)
                if parsed.scheme in ("https", "http") and parsed.hostname:
                    meta["url"] = value
                    break
            except ValueError:
                continue
    if "imageUrl" in record:
        meta["image_url"] = record["imageUrl"]
    return meta


def to_documents(source: str, response: dict) -> list[Document]:
    """Convert an already-fetched response without another API call.

    Search Documents contain each result's JSON, not fetched page text. Full
    provider envelopes remain available from FunctionTool.raw_output. Captions
    use one Document per segment; fullText is used only when segments are absent.
    """
    if source not in CONTRACTS or source == "youtube_download":
        raise ValueError("Select a readable source; downloads are job tools, not Documents.")
    documents = []
    for result_index, record in enumerate(response["results"]):
        base = {"source": source, "result_index": result_index}
        if source in ("youtube_transcript", "youtube_captions") and isinstance(record, dict):
            base.update(_source_metadata(record))
            base.update(
                {key: record[key] for key in ("languageCode", "isAutoGenerated") if key in record}
            )
            segments = record.get("segments")
            if isinstance(segments, list) and segments:
                for index, segment in enumerate(segments):
                    if isinstance(segment, dict) and isinstance(segment.get("text"), str):
                        metadata = {**base, "segment_index": index}
                        metadata.update(
                            {key: segment[key] for key in ("start", "end") if key in segment}
                        )
                        documents.append(Document(text=segment["text"], metadata=metadata))
                    else:
                        documents.append(
                            Document(
                                text=json.dumps(segment), metadata={**base, "segment_index": index}
                            )
                        )
                continue
            if isinstance(record.get("fullText"), str):
                documents.append(Document(text=record["fullText"], metadata=base))
                continue
        field = RESULT_FIELDS.get(source)
        if isinstance(record, dict) and field and isinstance(record.get(field), list):
            items = record[field]
        elif source == "youtube_suggestions" and isinstance(record, list):
            items = record
        else:
            items = [record]
        for item_index, item in enumerate(items):
            metadata = {**base, "item_index": item_index, **_source_metadata(item)}
            text = item if isinstance(item, str) else json.dumps(item, ensure_ascii=False)
            documents.append(Document(text=text, metadata=metadata))
    return documents


class FlashDataReader(BaseReader):
    """A source-specific remote reader. Inherited aload_data runs in a thread."""

    def __init__(self, source: str, *, api_key=None):
        if source not in CONTRACTS or source == "youtube_download":
            raise ValueError("Select a readable source; use download job tools for media delivery.")
        self.source = source
        self._execution = Execution(api_key)

    def load_data(self, **kwargs) -> list[Document]:
        result = self._execution.query(self.source, kwargs)
        return to_documents(self.source, result)
